#!/usr/bin/env python3
"""Bank-specific numbers for the JPMorgan read, from inputs.yaml and model-output.md only.

model.py has no section for a bank: its optimum, synthetic rating and FCFE treat deposits as financing.
This script computes what the course uses instead (lesson 11: levered betas, no relevering; lesson 20:
capital structure for a bank is regulatory capital against its requirement; lesson 26: FCFE for a bank =
net income − increase in regulatory capital; lesson 35: price-to-book against ROE).

Usage: python3 bank-equity.py inputs.yaml model-output.md > bank-equity-output.md
Every input is a ledger field or fact; the cost of equity is read from model-output.md section 1.
"""
import re
import sys

import yaml


def main(ledger_path, model_path):
    L = yaml.safe_load(open(ledger_path))
    F = {f["id"]: f["value"] for f in L["facts"]}
    v = lambda sec, k: L[sec][k]["value"]
    def ke_from(path):
        return float(re.search(r"\| Cost of equity \| ([\d.]+)% \| rf \+", open(path).read()).group(1)) / 100
    import os
    here = os.path.dirname(os.path.abspath(ledger_path))
    ke = ke_from(model_path)
    ke_mc = ke_from(os.path.join(here, "alternatives", "beta-money-center-output.md"))
    ke_mkt = ke_from(os.path.join(here, "alternatives", "beta-market-output.md"))
    pct = lambda x: "{:.1%}".format(x)
    pct2 = lambda x: "{:.2%}".format(x)
    m = lambda x: "${:,.0f}M".format(x)

    print("---")
    print('title: "JPMorgan Chase — bank equity calculations (generated)"')
    print("status: active")
    print("owner: weprintmoney")
    print("---")
    print()
    print("# Bank equity calculations")
    print()
    print("Generated by `bank-equity.py` from `inputs.yaml` and `model-output.md`. Do not edit by hand. Amounts in millions of USD.")
    print("Cost of equity from model-output.md section 1: {}.".format(pct2(ke)))
    print()

    # ---- A. Regulatory capital against requirements --------------------------------------------
    cet1 = F["cet1-capital-2026q1"]
    rwa_s, rwa_a = F["rwa-standardized-2026q1"], F["rwa-advanced-2026q1"]
    req = F["cet1-requirement-current"]
    gsib_now, gsib_2028 = 0.045, F["gsib-surcharge-2028-current-rules"]
    req_2028 = req + (gsib_2028 - gsib_now)
    req_reprop = req_2028 * (1 + F["required-cet1-change-under-reproposals"])
    print("## A. Regulatory capital at 2026-03-31 against requirements (leverage signal, bank version)")
    print()
    print("| Ratio | Actual | Requirement | Cushion (points) |")
    print("|---|---|---|---|")
    for lbl, a, r in [("CET1, Standardized", F["cet1-ratio-standardized-2026q1"], req),
                      ("CET1, Advanced (binding)", F["cet1-ratio-advanced-2026q1"], req),
                      ("Tier 1, Standardized", F["tier1-ratio-standardized-2026q1"], F["tier1-requirement"]),
                      ("Total capital, Standardized", F["total-capital-ratio-standardized-2026q1"], F["total-capital-requirement"]),
                      ("Tier 1 leverage", F["tier1-leverage-ratio-2026q1"], F["tier1-leverage-requirement"]),
                      ("Supplementary leverage (SLR)", F["slr-2026q1"], F["slr-requirement"])]:
        print("| {} | {} | {} | {:+.1f} |".format(lbl, pct(a), pct(r), (a - r) * 100))
    print()
    print("CET1 capital above each requirement (CET1 capital − requirement × binding RWA; Advanced RWA {} is the larger):".format(m(rwa_a)))
    print()
    print("| Requirement | Ratio | Required CET1 | Excess CET1 | Excess as share of market value |")
    print("|---|---|---|---|---|")
    E = v("company", "equity_value")
    rows = [("Current (4.5% min + 4.5% GSIB + 2.5% buffer)", req),
            ("2028 under current rules (GSIB surcharge 5.5%)", req_2028),
            ("2028 if the March 2026 re-proposals are adopted (+4% required CET1)", req_reprop)]
    for lbl, r in rows:
        need = r * max(rwa_s, rwa_a)
        print("| {} | {} | {} | {} | {} |".format(lbl, pct2(r), m(need), m(cet1 - need), pct(max(cet1 - need, 0) / E)))
    print()
    excess_now = cet1 - req * max(rwa_s, rwa_a)

    # ---- B. Bank FCFE against cash returned ------------------------------------------------------
    print("## B. Free cash flow to equity for a bank (lesson 26) against cash returned")
    print()
    print("FCFE = net income to common − increase in RWA × the CET1 ratio held. Shown at the current requirement "
          "({}), at the 2028 re-proposal level ({}), and at the ratio actually held at the start of the period. "
          "Cash returned = common dividends declared + buybacks.".format(pct2(req), pct2(req_reprop)))
    print()
    print("| Period | Net income to common | Increase in RWA | FCFE at {} | FCFE at {} | FCFE holding start ratio | Cash returned | Returned ÷ net income | Start → end CET1 ratio |".format(pct(req), pct(req_reprop)))
    print("|---|---|---|---|---|---|---|---|---|")
    periods = [("2024", "ni-common-2024", "rwa-standardized-2023", "rwa-standardized-2024", "common-dividends-2024", "buybacks-2024", "cet1-ratio-standardized-2023", "cet1-ratio-standardized-2024"),
               ("2025", "ni-common-2025", "rwa-standardized-2024", "rwa-standardized-2025", "common-dividends-2025", "buybacks-2025", "cet1-ratio-standardized-2024", "cet1-ratio-standardized-2025"),
               ("1Q26", "ni-common-2026q1", "rwa-standardized-2025", "rwa-standardized-2026q1", "common-dividends-2026q1", "buybacks-2026q1", "cet1-ratio-standardized-2025", "cet1-ratio-standardized-2026q1")]
    tot = dict(ni=0, ret=0, f1=0, f2=0)
    for lbl, ni_k, r0, r1, dv, bb, c0, c1 in periods:
        ni, d_rwa = F[ni_k], F[r1] - F[r0]
        f1, f2, f3 = ni - d_rwa * req, ni - d_rwa * req_reprop, ni - d_rwa * F[c0]
        ret = F[dv] + F[bb]
        tot["ni"] += ni; tot["ret"] += ret; tot["f1"] += f1; tot["f2"] += f2
        print("| {} | {} | {} | {} | {} | {} | {} | {} | {} → {} |".format(lbl, m(ni), m(d_rwa), m(f1), m(f2), m(f3), m(ret), pct(ret / ni), pct(F[c0]), pct(F[c1])))
    print("| **Total** | {} | | {} | {} | | {} | {} | |".format(m(tot["ni"]), m(tot["f1"]), m(tot["f2"]), m(tot["ret"]), pct(tot["ret"] / tot["ni"])))
    print()
    print("2025 RWA includes about $110,000M for the Apple Card forward commitment, cut to about $30,000M by 2026-03-31 (facts rwa-standardized-2025).")
    print()

    # ---- C. Returns against the cost of equity ---------------------------------------------------
    print("## C. Return on equity against the cost of equity")
    print()
    print("| Year | ROE (reported, average common equity) | Cost of equity (today's, section 1) | ROE − cost of equity |")
    print("|---|---|---|---|")
    for y, k in [("2023", "roe-reported-2023"), ("2024", "roe-reported-2024"), ("2025", "roe-reported-2025"), ("1Q26 annualized", "roe-reported-2026q1")]:
        print("| {} | {} | {} | {} |".format(y, pct(F[k]), pct2(ke), pct(F[k] - ke)))
    print()
    print("Segment ROE 1Q26: CCB {}, CIB {}, AWM {}. ROTCE 2025 {}, 1Q26 {}.".format(
        pct(F["roe-ccb-2026q1"]), pct(F["roe-cib-2026q1"]), pct(F["roe-awm-2026q1"]), pct(F["rotce-2025"]), pct(F["rotce-2026q1"])))
    print()

    # ---- D. Fundamental growth ----------------------------------------------------------------------
    roe25 = v("company", "net_income") / v("company", "equity_book")
    ret25 = (F["common-dividends-2025"] + F["buybacks-2025"]) / F["ni-common-2025"]
    print("## D. Growth implied by ROE and retention (lesson 31)")
    print()
    print("Expected growth in earnings = ROE × retention ratio. 2025: ROE on year-end common equity {} × (1 − {} returned) = {}.".format(
        pct(roe25), pct(ret25), pct(roe25 * (1 - ret25))))
    print()

    # ---- E. Price-to-book against ROE − cost of equity ---------------------------------------------
    px = v("company", "share_price")
    pb, ptb = px / F["bvps-2026q1"], px / F["tbvps-2026q1"]
    g = v("market", "terminal_growth")
    print("## E. Price-to-book against the gap between ROE and the cost of equity")
    print()
    print("Market price {} on 2026-06-30 ÷ book value per share {} (2026-03-31) = **{:.2f}x**; ÷ tangible book {} = {:.2f}x.".format(
        "${:.2f}".format(px), "${:.2f}".format(F["bvps-2026q1"]), pb, "${:.2f}".format(F["tbvps-2026q1"]), ptb))
    print()
    print("Justified price-to-book for a stable bank = (ROE − g) ÷ (cost of equity − g). Rows: sustained ROE; columns: cost of equity and growth.")
    print()
    kes = [("money-center beta", ke_mc), ("base", ke), ("market beta", ke_mkt)]
    gs = [0.02, g, 0.04]
    hdr = ["ke {} / g {}".format(pct2(k), pct(gg)) for _, k in kes for gg in gs]
    print("| Sustained ROE | " + " | ".join(hdr) + " |")
    print("|---|" + "---|" * len(hdr))
    for roe in [0.12, 0.14, 0.16, 0.17, 0.19]:
        cells = ["{:.2f}x".format((roe - gg) / (k - gg)) for _, k in kes for gg in gs]
        print("| {} | ".format(pct(roe)) + " | ".join(cells) + " |")
    print()
    print("Cost-of-equity columns come from alternatives/beta-money-center-output.md ({}), model-output.md ({}) and alternatives/beta-market-output.md ({}).".format(pct2(ke_mc), pct2(ke), pct2(ke_mkt)))
    print()
    print("ROE the market price implies (ROE = g + P/B × (ke − g)):")
    print()
    print("| Cost of equity | g | Implied sustained ROE |")
    print("|---|---|---|")
    for lbl, k in kes:
        for gg in gs:
            print("| {} ({}) | {} | {} |".format(pct2(k), lbl, pct(gg), pct(gg + pb * (k - gg))))
    print()

    # ---- F. Peers: price-to-book against ROE -------------------------------------------------------
    print("## F. Peers: price-to-book against ROE (lesson 35)")
    print()
    print("ROE here is FY2025 net income ÷ year-end equity from the peer file (common equity where preferred is tagged, total otherwise), so it is rough.")
    print()
    print("| Bank | P/B | ROE | Payout (dividends + buybacks ÷ net income) |")
    print("|---|---|---|---|")
    xs, ys = [], []
    for p in L["peers"]:
        pbp, roep = p["market_cap"] / p["equity_book"], p["net_income"] / p["equity_book"]
        xs.append(roep); ys.append(pbp)
        print("| {} | {:.2f}x | {} | {} |".format(p["ticker"], pbp, pct(roep), pct(p["payout"]) if p.get("payout") else "n/a"))
    print("| JPM | {:.2f}x | {} | {} |".format(E / v("company", "equity_book"), pct(roe25), pct(ret25)))
    n = len(xs); mx, my = sum(xs) / n, sum(ys) / n
    b = sum((x - mx) * (y - my) for x, y in zip(xs, ys)) / sum((x - mx) ** 2 for x in xs)
    a = my - b * mx
    ss_res = sum((y - (a + b * x)) ** 2 for x, y in zip(xs, ys)); ss_tot = sum((y - my) ** 2 for y in ys)
    print()
    print("Regression across the {} peers: P/B = {:.2f} + {:.2f} × ROE (R² {:.2f}). At JPM's {} ROE the peer line gives {:.2f}x against {:.2f}x actual.".format(
        n, a, b, 1 - ss_res / ss_tot, pct(roe25), a + b * roe25, E / v("company", "equity_book")))
    print()

    # ---- G. Buyback capacity -------------------------------------------------------------------------
    auth = F["buyback-authorization-2026"]
    print("## G. Capacity against the new authorization")
    print()
    print("Excess CET1 over the current requirement {} vs. the $50,000M authorization effective 2026-07-01 ({} of market value). "
          "At the 1Q26 pace ({} a quarter) the authorization lasts {:.1f} quarters.".format(
              m(excess_now), pct(auth / E), m(F["buybacks-2026q1"]), auth / F["buybacks-2026q1"]))


    # ---- H. Growth and debt figures the read quotes --------------------------------------------------
    print()
    print("## H. Growth and debt arithmetic quoted in the read")
    print()
    rev, ni_t = v("company", "revenue"), F["net-income-total-2025"]
    ltd0, ltd1 = F["long-term-debt-2025q1"], F["long-term-debt-2026q1"]
    print("| Item | Value | From |")
    print("|---|---|---|")
    print("| Revenue growth a year, 2022–25 | {} | revenue-2022 → company.revenue |".format(pct((rev / F["revenue-2022"]) ** (1 / 3) - 1)))
    print("| Net income growth a year, 2022–25 | {} | net-income-2022 → net-income-total-2025 |".format(pct((ni_t / F["net-income-2022"]) ** (1 / 3) - 1)))
    print("| Revenue growth 2025 | {} | revenue-2024 → company.revenue |".format(pct(rev / F["revenue-2024"] - 1)))
    print("| Net income growth 2025 | {} | net-income-total-2024 → 2025 |".format(pct(ni_t / F["net-income-total-2024"] - 1)))
    print("| 2026 NII outlook vs 2025 | {} | nii-2026-guidance ÷ nii-2025 |".format(pct(F["nii-2026-guidance"] / F["nii-2025"] - 1)))
    print("| 2026 adjusted expense outlook vs 2025 noninterest expense | {} | adjusted-expense-2026-guidance ÷ noninterest-expense-2025 |".format(pct(F["adjusted-expense-2026-guidance"] / F["noninterest-expense-2025"] - 1)))
    print("| Long-term debt growth, year to 2026-03-31 | {} | long-term-debt-2025q1 → 2026q1 |".format(pct(ltd1 / ltd0 - 1)))
    print("| Long-term debt growth, 2025 | {} | long-term-debt-2024 → 2025 |".format(pct(F["long-term-debt-2025"] / F["long-term-debt-2024"] - 1)))
    print("| Long-term debt 10% above 2026-03-31 | {} | 1.10 × long-term-debt-2026q1 |".format(m(1.1 * ltd1)))
    print("| Debt ratio if long-term debt were financing | {} | long-term debt ÷ (long-term debt + market value) |".format(pct(ltd1 / (ltd1 + E))))
    print("| Excess returned over bank FCFE, 2025 | {} to {} | section B: returned − FCFE at 11.5% and 13.0% |".format(
        m(F["common-dividends-2025"] + F["buybacks-2025"] - (F["ni-common-2025"] - (F["rwa-standardized-2025"] - F["rwa-standardized-2024"]) * req)),
        m(F["common-dividends-2025"] + F["buybacks-2025"] - (F["ni-common-2025"] - (F["rwa-standardized-2025"] - F["rwa-standardized-2024"]) * req_reprop))))
    own, med = map(float, re.search(r"\| Price / Book \| ([\d.]+)x \| ([\d.]+)x \|", open(model_path).read()).groups())
    print("| Peer-median P/B vs JPM | JPM {:.0%} above | model-output.md section 7 ({:.2f}x vs {:.2f}x) |".format(own / med - 1, own, med))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
