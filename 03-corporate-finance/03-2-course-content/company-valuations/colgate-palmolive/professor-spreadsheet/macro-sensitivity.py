"""Debt design inputs for Colgate-Palmolive (lesson 23).

Run from the company folder:
  python3 professor-spreadsheet/macro-sensitivity.py > professor-spreadsheet/macro-sensitivity-output.md

1. Bottom-up: sector sensitivities from the professor's macrodur.xlsx (Sector Averages by SIC).
2. Top-down: Colgate's own operating income and firm value regressed on the workbook's annual macro data.
3. The debt Colgate has: maturity and currency from the rated notes in Capital IQ.
"""
import csv, re, sys, site, warnings, datetime
sys.path.append(site.getusersitepackages())
import openpyxl
warnings.simplefilter("ignore")

WB = "professor-spreadsheet/originals/macrodur.xlsx"
FACTS = "sources/filings/cl-multi-year-financials-fy2014-fy2025.tsv"
RATINGS = "sources/capital-iq/credit-ratings.tsv"
# Year-end dividend-adjusted and plain closes are not both needed; firm value uses the plain close.
CLOSE = {2016: 65.44, 2017: 75.45, 2018: 59.52, 2019: 68.84, 2020: 85.51, 2021: 85.34,
         2022: 78.79, 2023: 79.71, 2024: 90.91, 2025: 79.02}  # Yahoo Finance chart endpoint, read 2026-11-21
ANALYSIS = datetime.date(2026, 11, 20)

wb = openpyxl.load_workbook(WB, data_only=True)

def ols(x, y):
    n = len(x); mx = sum(x) / n; my = sum(y) / n
    sxx = sum((a - mx) ** 2 for a in x); sxy = sum((a - mx) * (b - my) for a, b in zip(x, y))
    b = sxy / sxx; a = my - b * mx
    sse = sum((yy - a - b * xx) ** 2 for xx, yy in zip(x, y)); sst = sum((yy - my) ** 2 for yy in y)
    se = (sse / (n - 2) / sxx) ** 0.5
    return b, se, 1 - sse / sst, n

print("---\ntitle: \"Colgate-Palmolive (CL) — macro sensitivity and debt profile\"\nstatus: draft\nowner: weprintmoney\ncreated: 2026-11-21\nlast_updated: 2026-11-21\n---\n")
print("# Macro sensitivity and debt profile\n\nGenerated by `professor-spreadsheet/macro-sensitivity.py`. Do not edit by hand.\n")

# 1. bottom-up
print("## 1. Bottom-up: sector averages from macrodur.xlsx\n")
print("The workbook's sector table uses quarterly data for 1987–1997. Its note says to use the firm-value columns for duration and cyclicality and the operating-income columns for inflation and currency. Duration is shown as the negative of the interest-rate coefficient.\n")
sec = {}
for r in wb["Sector Averages by SIC"].iter_rows(values_only=True):
    if isinstance(r[0], (int, float)) and r[2] is not None:
        sec[int(r[0])] = r
mix = [(2844, 0.7737, "Oral, Personal and Home Care (Colgate's own SIC code)"), (2040, 0.2263, "Hill's Pet Nutrition (pet food is SIC 2047, inside group 204; 2047 is not in the table)")]
print("| SIC | Industry | Used for | Weight | Duration | Cyclicality | Inflation | Currency |\n|---|---|---|---|---|---|---|---|")
tot = [0, 0, 0, 0]
for sic, w, what in mix:
    r = sec[sic]; vals = [-r[2], r[3], r[8], r[9]]
    tot = [t + w * v for t, v in zip(tot, vals)]
    print(f"| {sic} | {r[1]} | {what} | {w:.2%} | {vals[0]:.2f} | {vals[1]:.2f} | {vals[2]:.2f} | {vals[3]:.2f} |")
print(f"| | **Weighted** | | 100% | **{tot[0]:.2f}** | **{tot[1]:.2f}** | **{tot[2]:.2f}** | **{tot[3]:.2f}** |")
r = sec[2840]
print(f"\nCross-check, SIC 2840 ({r[1]}): duration {-r[2]:.2f}, cyclicality {r[3]:.2f}, inflation {r[8]:.2f}, currency {r[9]:.2f}.\n")

# 2. top-down
facts = {}
for row in csv.reader(open(FACTS), delimiter="\t"):
    if row[0] == "taxonomy": hdr = row; continue
    facts[row[1]] = {int(y): float(v) / 1e6 for y, v in zip(hdr[3:], row[3:]) if v != ""}
macro = {}
for r in wb["Annual Data"].iter_rows(min_row=2, values_only=True):
    if isinstance(r[0], (int, float)): macro[int(r[0])] = {"rate": r[2], "gdp": r[4], "cpi": r[6], "usd": r[8]}
oi = dict(facts["OperatingIncomeLoss"])
for y, v in facts.get("GoodwillAndIntangibleAssetImpairment", {}).items(): oi[y] = oi[y] + v   # add back non-cash write-downs
debt = {}
for y in CLOSE:
    d = facts.get("LongTermDebtAndCapitalLeaseObligationsIncludingCurrentMaturities", {}).get(y) or facts.get("LongTermDebt", {}).get(y)
    if d is not None: debt[y] = d
sh = facts["WeightedAverageNumberOfSharesOutstandingBasic"]
fv = {y: CLOSE[y] * sh[y] + debt[y] for y in CLOSE if y in debt}
print("## 2. Top-down: Colgate's own history\n")
print("Annual data. Operating income is as reported with goodwill and intangible write-downs added back. Firm value is the year-end close times weighted basic shares, plus long-term debt. Each cell is a one-variable regression of the percentage change on the macro variable from the workbook's Annual Data sheet.\n")
print("| Year | Operating income | Firm value |\n|---|---|---|")
for y in sorted(oi):
    if y >= 2014: print(f"| {y} | {oi[y]:,.0f} | {fv[y]:,.0f} |" if y in fv else f"| {y} | {oi[y]:,.0f} | n/a |")
def chg(series):
    ys = sorted(series); return {b: series[b] / series[a] - 1 for a, b in zip(ys, ys[1:]) if b - a == 1}
print("\n| Dependent variable | Macro variable | Coefficient | Std. error | R² | Years |\n|---|---|---|---|---|---|")
for name, ser in (("% change in operating income", chg({y: v for y, v in oi.items() if y >= 2014})), ("% change in firm value", chg(fv))):
    for key, label in (("rate", "Change in 10-year rate"), ("gdp", "Real GDP growth"), ("cpi", "Change in inflation"), ("usd", "% change in the dollar")):
        ys = [y for y in sorted(ser) if y in macro and macro[y][key] is not None]
        b, se, r2, n = ols([macro[y][key] for y in ys], [ser[y] for y in ys])
        print(f"| {name} | {label} | {b:.2f} | {se:.2f} | {r2:.2f} | {n} |")

# 3. actual debt
print("\n## 3. The debt Colgate has (rated notes, Capital IQ)\n")
rows = []; seen = set()
for line in open(RATINGS):
    p = line.rstrip("\n").split("\t")
    if len(p) < 2 or not re.match(r"[A-Z][a-z]{2}-\d\d-\d{4}", p[0]): continue
    m = re.match(r"(US\$|EUR)([\d.]+) mil (.*)", p[1])
    if not m or p[1] in seen: continue
    seen.add(p[1])
    mat = datetime.datetime.strptime(p[0], "%b-%d-%Y").date()
    rows.append((m.group(1), float(m.group(2)), mat, "fltg" in m.group(3)))
EURUSD = 587.1 / 500   # Capital IQ carries each EUR500 note at USD587.1 (capital-structure-details.tsv)
tot = 0; wy = 0; eur = 0; flt = 0
for cur, amt, mat, f in rows:
    usd = amt * (EURUSD if cur == "EUR" else 1); yrs = (mat - ANALYSIS).days / 365.25
    tot += usd; wy += usd * yrs; eur += usd if cur == "EUR" else 0; flt += usd if f else 0
print(f"| Item | Value |\n|---|---|\n| Notes counted | {len(rows)} |\n| Principal, $M (euro notes at {EURUSD:.3f}) | {tot:,.0f} |\n| Weighted average maturity, years from 2026-11-20 | {wy / tot:.1f} |\n| Euro-denominated share | {eur / tot:.1%} |\n| Floating-rate share | {flt / tot:.1%} |")
print("\nMaturity is not duration: with coupons averaging 2.9%, duration is shorter than the weighted maturity.")
