def wacc(ke, kd=kd_actual):
    return (1 - wd) * ke + wd * kd * (1 - t)


def pct(x, n=2):
    return f"{x * 100:.{n}f}%"


def ols(x, y):
    n = len(x); mx = sum(x) / n; my = sum(y) / n
    sxx = sum((a - mx) ** 2 for a in x); syy = sum((b - my) ** 2 for b in y)
    sxy = sum((a - mx) * (b - my) for a, b in zip(x, y))
    b = sxy / sxx; a = my - b * mx; sse = syy - b * sxy
    return dict(n=n, beta=b, alpha=a, se=math.sqrt(sse / (n - 2) / sxx), r2=1 - sse / syy,
                sd_y=math.sqrt(syy / (n - 1)), sd_x=math.sqrt(sxx / (n - 1)), mean_x=mx, mean_y=my)


