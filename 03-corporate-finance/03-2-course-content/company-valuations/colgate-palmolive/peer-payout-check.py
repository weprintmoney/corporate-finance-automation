"""Five-year dividends and buybacks against net income for Colgate and six household peers.

Run from the company folder:  python3 peer-payout-check.py > peer-payout-check-output.md
Source: sources/capital-iq/peer-cash-returned.tsv (Capital IQ cash flow statements, each company's last five fiscal years).
"""
import csv, statistics as st
def num(s):
    s = s.strip()
    if s in ("", "-"): return 0.0
    v = float(s.replace("(", "").replace(")", "").replace(",", ""))
    return -v if s.startswith("(") else v
data = {}
for r in csv.reader(open("sources/capital-iq/peer-cash-returned.tsv"), delimiter="\t"):
    if len(r) >= 2 and r[1] in ("currency", "net_income", "dividends", "buybacks", "issuance"):
        data.setdefault(r[0], {})[r[1]] = (r[2:7] + [""] * 5)[:5]
print('---\ntitle: "Colgate-Palmolive (CL) — peer payout check"\nstatus: active\nowner: weprintmoney\ncreated: 2026-11-21\nlast_updated: 2026-11-21\n---\n')
print("# Cash returned against net income, last five fiscal years\n\nGenerated by `peer-payout-check.py`. Do not edit by hand. Amounts in millions of each company's reporting currency.\n")
print("| Company | Currency | Net income | Dividends | Buybacks | Share issuance | Dividends ÷ net income | Dividends + buybacks ÷ net income | Net of issuance ÷ net income |\n|---|---|---|---|---|---|---|---|---|")
rows = {}
for name, d in data.items():
    ni = sum(map(num, d["net_income"])); dv = -sum(map(num, d["dividends"])); bb = -sum(map(num, d["buybacks"])); iss = sum(map(num, d.get("issuance", [])))
    rows[name] = (dv / ni, (dv + bb) / ni, (dv + bb - iss) / ni)
    print(f"| {name} | {d['currency'][0]} | {ni:,.0f} | {dv:,.0f} | {bb:,.0f} | {iss:,.0f} | {dv/ni:.1%} | {(dv+bb)/ni:.1%} | {(dv+bb-iss)/ni:.1%} |")
peers = [v for k, v in rows.items() if "Colgate" not in k]
print(f"| **Median of the six peers** | | | | | | **{st.median(p[0] for p in peers):.1%}** | **{st.median(p[1] for p in peers):.1%}** | **{st.median(p[2] for p in peers):.1%}** |")
print("\nColgate's net income carries 2,211 of write-downs over the five years. On net income before them (13,483) its three ratios are " + ", ".join(f"{x:.1%}" for x in (8731/13483, (8731+6705)/13483, (8731+6705-1961)/13483)) + ".")
