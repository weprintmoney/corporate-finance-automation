#!/usr/bin/env python3
"""Run the numeric spine of a /value-company valuation from a ledger (inputs.yaml).

Sections, in course order:
  1. Cost of capital at actual weights (and at book weights, if book values are in the ledger)
  2. Synthetic rating from interest coverage, under each numerator the ledger supplies
  3. Optimal debt ratio: the iterative rating loop from 0% to 70% debt, per numerator
  4. Stress test: operating income down 10%, 20%, 30%
  5. Free cash flow to equity vs. cash returned, for each year in company.history
  6. DCF: explicit forecast, terminal value (two methods), bridge to value per share
  7. Relative valuation: the company's multiples against the peer median

Usage: python3 model.py <inputs.yaml> > model-output.md

Everything printed is computed from the ledger. Nothing here is a judgment call; the judgment
calls are the modeling_choices block in the ledger, which this script reports but does not make.
Method follows company-valuations/solarwinds/tools/capital-structure-rerun.py, generalized.
"""
import statistics
import sys

import yaml

# Damodaran's ratings tables from lesson 18, spreadsheet-cost-of-capital-optimal.md,
# "Default Spreads and Ratios". Each row: (coverage ratio must be greater than, spread).
LARGE = [(-1e5, .14), (.2, .105), (.65, .08), (.8, .065), (1.25, .055), (1.5, .045), (1.75, .0375),
         (2, .03), (2.25, .025), (2.5, .016), (3, .0125), (4.25, .011), (5.5, .01), (6.5, .008), (8.5, .006)]
SMALL = [(-1e5, .14), (.5, .105), (.8, .08), (1.25, .065), (1.5, .055), (2, .045), (2.5, .0375),
         (3, .03), (3.5, .025), (4, .016), (4.5, .0125), (6, .011), (7.5, .01), (9.5, .008), (12.5, .006)]
RATINGS = ["D", "C", "CC", "CCC", "B-", "B", "B+", "BB", "BB+", "BBB", "A-", "A", "A+", "AA", "AAA"]


class Ledger:
    def __init__(self, data):
        self.d = data

    def get(self, path, default=None):
        cur = self.d
        for key in path.split("."):
            if not isinstance(cur, dict) or key not in cur:
                return default
            cur = cur[key]
        if isinstance(cur, dict) and "value" in cur:
            return cur["value"]
        return cur if cur is not None else default

    def num(self, path, default=None):
        val = self.get(path, default)
        return float(val) if isinstance(val, (int, float)) and not isinstance(val, bool) else default


def money(x):
    return "${:,.1f}M".format(x)


def pct(x):
    return "{:.2%}".format(x)


def spread_for(cov, table):
    spread, rating = table[0][1], RATINGS[0]
    for (lo, sp), name in zip(table, RATINGS):
        if cov > lo:
            spread, rating = sp, name
    return spread, rating


def spread_for_rating(rating, table):
    name = str(rating).split("/")[-1].strip()
    for (lo, sp), rname in zip(table, RATINGS):
        if rname == name:
            return sp
    return None


def wacc_at(d, V, numerator, bu, rf, erp, t, table):
    """Damodaran's loop: debt -> interest -> coverage -> rating -> rate, iterated to a fixed point."""
    D = d * V
    kd = rf + .02
    for _ in range(50):
        cov = numerator / (D * kd) if D else 1e9
        sp, rating = spread_for(cov, table)
        kd = rf + sp
    interest = D * kd
    teff = t if interest <= numerator or not D else t * max(numerator, 0) / interest
    bl = bu * (1 + (1 - teff) * d / (1 - d)) if d < 1 else float("inf")
    ke = rf + bl * erp
    return (1 - d) * ke + d * kd * (1 - teff), (numerator / interest if D else None), rating, kd


def optimum(V, numerator, bu, rf, erp, t, table):
    grid = [x / 100 for x in range(0, 71)]
    rows = [(d,) + wacc_at(d, V, numerator, bu, rf, erp, t, table) for d in grid]
    best = min(rows, key=lambda r: r[1])
    return best, rows


def main(path):
    with open(path) as fh:
        L = Ledger(yaml.safe_load(fh))

    company = L.get("meta.company")
    base_year = L.get("meta.base_year")
    currency = L.get("meta.currency")
    print("# Model output: {} (base year {})".format(company, base_year))
    print()
    print("Generated by `.claude/skills/value-company/tools/model.py` from `{}`. Do not edit by hand; "
          "change the ledger and rerun.".format(path))
    print("Amounts in millions of {}. Rates as percentages. Ratings from Damodaran's {}-firm table.".format(
        currency, L.get("modeling_choices.firm_size_table", "small")))
    print()

    # ---- inputs -------------------------------------------------------------------------------
    rf = L.num("market.risk_free_rate")
    erp = L.num("country.weighted_erp") or L.num("market.mature_erp")
    t = L.num("market.tax_rate_marginal")
    g = L.num("market.terminal_growth")
    bu = L.num("beta.unlevered_bottom_up")
    table = LARGE if L.get("modeling_choices.firm_size_table") == "large" else SMALL
    D = L.num("company.debt_total")
    E = L.num("company.equity_value")
    cash = L.num("company.cash", 0.0)
    ebit = L.num("company.ebit")
    interest = L.num("company.interest_expense")
    for name, val in [("market.risk_free_rate", rf), ("equity risk premium", erp), ("market.tax_rate_marginal", t),
                      ("market.terminal_growth", g), ("beta.unlevered_bottom_up", bu), ("company.debt_total", D),
                      ("company.equity_value", E), ("company.ebit", ebit), ("company.interest_expense", interest)]:
        if val is None:
            sys.exit("model.py: ledger is missing {}".format(name))

    V = D + E
    d = D / V
    print("## Modeling choices (from the ledger)")
    print()
    for key in ["coverage_numerator", "firm_size_table", "sbc_treatment", "firm_value_basis", "beta_source",
                "kd_source", "terminal_method"]:
        print("- {}: {}".format(key, L.get("modeling_choices." + key, "(default)")))
    print()

    # ---- 1. cost of capital ---------------------------------------------------------------------
    bl = bu * (1 + (1 - t) * D / E)
    ke = rf + bl * erp
    kd_source = L.get("modeling_choices.kd_source", "observed")
    cov_ebit = ebit / interest if interest else None
    syn_spread, syn_rating = spread_for(cov_ebit if cov_ebit is not None else 1e9, table)
    kd_observed = L.num("debt.kd_pretax_observed")
    rating_actual = L.get("debt.rating_actual")
    if kd_source == "observed" and kd_observed is not None:
        kd, kd_label = kd_observed, "observed rate on the company's own debt"
    elif kd_source == "actual_rating" and rating_actual and spread_for_rating(rating_actual, table) is not None:
        kd, kd_label = rf + spread_for_rating(rating_actual, table), "risk-free rate plus the spread for the {} agency rating".format(rating_actual)
    else:
        kd, kd_label = rf + syn_spread, "risk-free rate plus the synthetic-rating spread ({})".format(syn_rating)
    teff = t if interest <= ebit else t * max(ebit, 0) / interest
    wacc = (1 - d) * ke + d * kd * (1 - teff)

    print("## 1. Cost of capital at market weights")
    print()
    print("| Item | Value | How |")
    print("|---|---|---|")
    print("| Debt (D) | {} | company.debt_total |".format(money(D)))
    print("| Equity (E) | {} | company.equity_value |".format(money(E)))
    print("| Firm value (V = D + E) | {} | arithmetic |".format(money(V)))
    print("| Debt ratio (D/V) | {} | arithmetic |".format(pct(d)))
    print("| Debt to equity (D/E) | {:.4f} | arithmetic |".format(D / E))
    print("| Unlevered beta | {:.4f} | beta.unlevered_bottom_up |".format(bu))
    print("| Levered beta | {:.4f} | unlevered × (1 + (1 − t) × D/E) |".format(bl))
    print("| Risk-free rate | {} | market.risk_free_rate |".format(pct(rf)))
    print("| Equity risk premium | {} | country.weighted_erp |".format(pct(erp)))
    print("| Cost of equity | {} | rf + levered beta × ERP |".format(pct(ke)))
    print("| Pre-tax cost of debt | {} | {} |".format(pct(kd), kd_label))
    print("| Marginal tax rate | {} | market.tax_rate_marginal |".format(pct(t)))
    if teff != t:
        print("| Effective tax benefit on interest | {} | interest exceeds operating income, so only part of it is deductible |".format(pct(teff)))
    print("| After-tax cost of debt | {} | pre-tax × (1 − t) |".format(pct(kd * (1 - teff))))
    print("| **Cost of capital (WACC)** | **{}** | E/V × ke + D/V × kd × (1 − t) |".format(pct(wacc)))
    Eb, Db = L.num("company.equity_book"), (L.num("company.debt_book") or L.num("company.debt_face"))
    if Eb and Db:
        Vb = Eb + Db
        wacc_book = (Eb / Vb) * ke + (Db / Vb) * kd * (1 - teff)
        print("| Cost of capital at book weights | {} | book D/V = {} ; for lesson 13's comparison only |".format(pct(wacc_book), pct(Db / Vb)))
    print()

    # ---- 2. synthetic rating --------------------------------------------------------------------
    numerators = [("EBIT", ebit)]
    amort = L.num("company.acquisition_amortization")
    if amort:
        numerators.append(("EBIT + acquisition amortization", ebit + amort))
    ebitda = L.num("company.ebitda_standardized")
    if ebitda:
        numerators.append(("EBITDA (standardized)", ebitda))
    ebitda_adj = L.num("company.ebitda_adjusted")
    print("## 2. Interest coverage and synthetic rating")
    print()
    print("| Numerator | Amount | Interest | Coverage | Synthetic rating | Spread | Implied pre-tax cost of debt |")
    print("|---|---|---|---|---|---|---|")
    for label, num in numerators:
        cov = num / interest
        sp, r = spread_for(cov, table)
        print("| {} | {} | {} | {:.2f}x | {} | {} | {} |".format(label, money(num), money(interest), cov, r, pct(sp), pct(rf + sp)))
    if ebitda_adj:
        cov = ebitda_adj / interest
        sp, r = spread_for(cov, table)
        print("| Company-adjusted EBITDA (adds back stock-based compensation; shown, not used) | {} | {} | {:.2f}x | {} | {} | {} |".format(
            money(ebitda_adj), money(interest), cov, r, pct(sp), pct(rf + sp)))
    print()
    print("Agency rating in the ledger: {}.".format(rating_actual if rating_actual else "none disclosed"))
    print()

    # ---- 3. optimal debt ratio --------------------------------------------------------------------
    print("## 3. Optimal debt ratio (cost of capital approach)")
    print()
    print("Firm value held at {} ({} basis). Unlevered beta relevered at each debt ratio; the rating and the "
          "interest rate are iterated until they agree.".format(money(V), L.get("modeling_choices.firm_value_basis", "market")))
    print()
    chosen = L.get("modeling_choices.coverage_numerator", "ebit")
    chosen_label = {"ebit": "EBIT", "ebit_plus_acquisition_amortization": "EBIT + acquisition amortization",
                    "ebitda": "EBITDA (standardized)"}.get(chosen, "EBIT")
    results = {}
    print("| Coverage numerator | Optimal debt ratio | WACC at optimum | Rating at optimum | WACC at current ratio (same method) | Annual savings from moving | Value of moving (perpetuity at g) | Debt above (+) or below (−) optimum |")
    print("|---|---|---|---|---|---|---|---|")
    for label, num in numerators:
        (dopt, w_opt, cov_opt, r_opt, _), rows = optimum(V, num, bu, rf, erp, t, table)
        w_cur = wacc_at(d, V, num, bu, rf, erp, t, table)[0]
        savings = (w_cur - w_opt) * V
        gain = savings / (w_opt - g) if w_opt > g else float("nan")
        results[label] = dict(dopt=dopt, w_opt=w_opt, w_cur=w_cur, gain=gain, rows=rows)
        mark = " (chosen)" if label == chosen_label else ""
        print("| {}{} | {:.0%} | {} | {} | {} | {} | {} | {} |".format(
            label, mark, dopt, pct(w_opt), r_opt, pct(w_cur), money(savings), money(gain), money((d - dopt) * V)))
    print()
    print("### Schedule under the chosen numerator ({})".format(chosen_label))
    print()
    print("| Debt ratio | Levered beta | Cost of equity | Coverage | Rating | Pre-tax cost of debt | WACC |")
    print("|---|---|---|---|---|---|---|")
    rows = results.get(chosen_label, results["EBIT"])["rows"]
    dopt = results.get(chosen_label, results["EBIT"])["dopt"]
    for (dd, w, cov, r, kd_d) in rows:
        if round(dd * 100) % 10 == 0 or abs(dd - dopt) < 1e-9 or abs(dd - round(d, 2)) < 1e-9:
            bl_d = bu * (1 + (1 - t) * dd / (1 - dd))
            flag = " ← optimum" if abs(dd - dopt) < 1e-9 else (" ← current" if abs(dd - round(d, 2)) < 1e-9 else "")
            print("| {:.0%}{} | {:.3f} | {} | {} | {} | {} | {} |".format(
                dd, flag, bl_d, pct(rf + bl_d * erp), ("{:.2f}x".format(cov) if cov else "n/a"), r, pct(kd_d), pct(w)))
    print()

    # ---- 4. stress test --------------------------------------------------------------------------
    print("## 4. Stress test: operating income lower")
    print()
    chosen_num = dict(numerators).get(chosen_label, ebit)
    print("| Operating income | Numerator used | Optimal debt ratio | WACC at optimum |")
    print("|---|---|---|---|")
    for cut in [0.0, 0.1, 0.2, 0.3]:
        num = chosen_num * (1 - cut)
        (dopt_s, w_s, _, _, _), _ = optimum(V, num, bu, rf, erp, t, table)
        print("| down {:.0%} | {} | {:.0%} | {} |".format(cut, money(num), dopt_s, pct(w_s)))
    print()

    # ---- 5. FCFE vs cash returned ------------------------------------------------------------------
    hist = L.get("company.history") or []
    if hist:
        print("## 5. Free cash flow to equity vs. cash returned")
        print()
        print("FCFE = net income − (capex − D&A) − change in working capital + (debt issued − debt repaid). "
              "Cash returned = dividends + buybacks.")
        print()
        print("| Year | Net income | Net capex | Change in WC | Net new debt | FCFE | Cash returned | Returned − FCFE | Cash balance |")
        print("|---|---|---|---|---|---|---|---|---|")
        tot_fcfe = tot_ret = 0.0
        for r in hist:
            ni, da_, cx, wc = r.get("net_income", 0.0), r.get("da", 0.0), r.get("capex", 0.0), r.get("change_wc", 0.0)
            nd = r.get("debt_issued", 0.0) - r.get("debt_repaid", 0.0)
            fcfe = ni - (cx - da_) - wc + nd
            ret = r.get("dividends", 0.0) + r.get("buybacks", 0.0)
            tot_fcfe += fcfe
            tot_ret += ret
            print("| {} | {} | {} | {} | {} | {} | {} | {} | {} |".format(
                r.get("year"), money(ni), money(cx - da_), money(wc), money(nd), money(fcfe), money(ret), money(ret - fcfe), money(r.get("cash", 0.0))))
        print("| **Total** | | | | | **{}** | **{}** | **{}** | change {} |".format(
            money(tot_fcfe), money(tot_ret), money(tot_ret - tot_fcfe), money(hist[-1].get("cash", 0.0) - hist[0].get("cash", 0.0))))
        print()

    # ---- 6. DCF -------------------------------------------------------------------------------------
    years = L.get("forecast.years") or []
    if years:
        print("## 6. Discounted cash flow")
        print()
        fcffs, derived = [], False
        s2c = L.num("forecast.sales_to_capital")
        prev_rev = L.num("company.revenue")
        for r in years:
            if r.get("fcff") is not None:
                fcffs.append(float(r["fcff"]))
            else:
                derived = True
                rev, margin = float(r["revenue"]), float(r["ebit_margin"])
                reinvest = (rev - prev_rev) / s2c if s2c and prev_rev is not None else 0.0
                fcffs.append(rev * margin * (1 - t) - reinvest)
            prev_rev = float(r.get("revenue", prev_rev or 0.0))
        n = len(fcffs)
        wacc_stable = L.num("forecast.wacc_stable") or wacc
        roic_stable = L.num("forecast.stable_roic")
        method = L.get("modeling_choices.terminal_method", "consistent_reinvestment")
        last = years[-1]
        tv_growth = fcffs[-1] * (1 + g) / (wacc_stable - g)
        tv_consistent = None
        if roic_stable and last.get("revenue") is not None and last.get("ebit_margin") is not None:
            ebit_next = float(last["revenue"]) * (1 + g) * float(last["ebit_margin"])
            tv_consistent = ebit_next * (1 - t) * (1 - g / roic_stable) / (wacc_stable - g)
        tv = tv_consistent if (method == "consistent_reinvestment" and tv_consistent is not None) else tv_growth
        pv_explicit = sum(cf / (1 + wacc) ** (i + 1) for i, cf in enumerate(fcffs))
        pv_tv = tv / (1 + wacc) ** n
        ev = pv_explicit + pv_tv
        mi = L.num("company.minority_interests", 0.0)
        xh = L.num("company.cross_holdings", 0.0)
        opt = L.num("company.options_value", 0.0)
        equity = ev - D + cash - mi + xh
        sb, sd = L.num("company.shares_basic"), L.num("company.shares_diluted")
        print("Cash flows {} from the ledger's forecast{}. Discounted at the current cost of capital {}; terminal "
              "value at {} with perpetual growth {}.".format(
                  "derived" if derived else "taken", " (revenue × margin × (1 − t) − reinvestment)" if derived else "",
                  pct(wacc), pct(wacc_stable), pct(g)))
        print()
        print("| Year | FCFF | Discount factor | Present value |")
        print("|---|---|---|---|")
        for i, (r, cf) in enumerate(zip(years, fcffs)):
            print("| {} | {} | {:.4f} | {} |".format(r.get("year"), money(cf), 1 / (1 + wacc) ** (i + 1), money(cf / (1 + wacc) ** (i + 1))))
        print()
        print("| Terminal value | Amount | Method |")
        print("|---|---|---|")
        print("| Final-year FCFF grown at g | {} | FCFF × (1 + g) ÷ (WACC − g){} |".format(money(tv_growth), " ← used" if tv is tv_growth else ""))
        if tv_consistent is not None:
            print("| Consistent reinvestment | {} | after-tax EBIT × (1 − g ÷ stable ROIC {}) ÷ (WACC − g){} |".format(
                money(tv_consistent), pct(roic_stable), " ← used" if tv is tv_consistent else ""))
            print("| Terminal reinvestment rate | {} | g ÷ stable ROIC |".format(pct(g / roic_stable)))
        print()
        print("| Bridge | Amount |")
        print("|---|---|")
        print("| Present value of explicit cash flows | {} |".format(money(pv_explicit)))
        print("| Present value of terminal value | {} |".format(money(pv_tv)))
        print("| **Enterprise value** | **{}** |".format(money(ev)))
        print("| − Debt | {} |".format(money(D)))
        print("| + Cash | {} |".format(money(cash)))
        if mi:
            print("| − Minority interests | {} |".format(money(mi)))
        if xh:
            print("| + Cross-holdings | {} |".format(money(xh)))
        print("| = Equity value before option claims | {} |".format(money(equity)))
        if sb:
            print("| − Value of options and RSUs | {} |".format(money(opt)))
            print("| **Value per share (course method: ÷ basic shares {:.1f}M)** | **${:.2f}** |".format(sb, (equity - opt) / sb))
        if sd:
            print("| Value per share (shortcut: ÷ diluted shares {:.1f}M, options ignored) | ${:.2f} |".format(sd, equity / sd))
        price = L.num("company.share_price")
        if price and sb:
            print("| Market or transaction price ({}) | ${:.2f} |".format(L.get("meta.price_basis", "market"), price))
            print("| Course-method value ÷ price | {:.2f}x |".format(((equity - opt) / sb) / price))
        print()
        # financing lever of the value of control
        res = results.get(chosen_label, results["EBIT"])
        if res["w_opt"] < wacc:
            pv_e2 = sum(cf / (1 + res["w_opt"]) ** (i + 1) for i, cf in enumerate(fcffs))
            ws2 = res["w_opt"] if L.num("forecast.wacc_stable") is None else wacc_stable
            # same terminal cash flow as above, capitalized at the optimal stable rate
            tv2_amt = tv * (wacc_stable - g) / (ws2 - g)
            ev2 = pv_e2 + tv2_amt / (1 + res["w_opt"]) ** n
            eq2 = ev2 - D + cash - mi + xh - opt
            print("Value of control, financing lever only: at the optimal cost of capital {} the enterprise value is {} "
                  "and value per share (course method) is ${:.2f}, against ${:.2f} at the status quo. The other levers "
                  "(operations, reinvestment, growth period) are judgment calls answered in lesson 34, not computed here.".format(
                      pct(res["w_opt"]), money(ev2), eq2 / sb if sb else float("nan"), (equity - opt) / sb if sb else float("nan")))
            print()

    # ---- 7. multiples -------------------------------------------------------------------------------
    peers = L.get("peers") or []
    rev = L.num("company.revenue")
    ni = L.num("company.net_income")
    if rev:
        print("## 7. Relative valuation")
        print()
        ev_co = E + D - cash
        print("Company enterprise value = equity {} + debt {} − cash {} = {}.".format(money(E), money(D), money(cash), money(ev_co)))
        print()
        print("| Multiple | {} | Peer median | Peers used |".format(company))
        print("|---|---|---|---|")

        def med(vals):
            vals = [v for v in vals if v is not None]
            return (statistics.median(vals), len(vals)) if vals else (None, 0)

        def ratio(a, b):
            return a / b if a is not None and b not in (None, 0) and b > 0 else None

        rows_m = [
            ("EV / Revenue", ratio(ev_co, rev), med([ratio(p.get("enterprise_value"), p.get("revenue")) for p in peers])),
            ("EV / EBITDA", ratio(ev_co, ebitda), med([ratio(p.get("enterprise_value"), p.get("ebitda")) for p in peers])),
            ("Price / Earnings", ratio(E, ni), med([ratio(p.get("market_cap"), p.get("net_income")) for p in peers])),
            ("Price / Book", ratio(E, Eb), med([ratio(p.get("market_cap"), p.get("equity_book")) for p in peers])),
        ]
        for label, own, (m, k) in rows_m:
            print("| {} | {} | {} | {} |".format(label, "{:.2f}x".format(own) if own else "n/a", "{:.2f}x".format(m) if m else "n/a", k))
        print()
        sb = L.num("company.shares_basic")
        if sb:
            m_rev = rows_m[0][2][0]
            m_ebitda = rows_m[1][2][0]
            if m_rev:
                print("- At the peer-median EV/Revenue of {:.2f}x, implied value per share = (({:.2f} × {}) − debt + cash) ÷ {:.1f}M shares = ${:.2f}.".format(
                    m_rev, m_rev, money(rev), sb, (m_rev * rev - D + cash) / sb))
            if m_ebitda and ebitda:
                print("- At the peer-median EV/EBITDA of {:.2f}x, implied value per share = ${:.2f}.".format(
                    m_ebitda, (m_ebitda * ebitda - D + cash) / sb))
        print()
        print("Peer rows marked `estimate: true` in the ledger carry ranges; the medians above use the point values.")
        print()


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit("usage: model.py <inputs.yaml>")
    main(sys.argv[1])
