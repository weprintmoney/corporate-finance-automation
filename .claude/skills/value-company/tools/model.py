                flag = " ← APV optimum" if dd == best_apv[0] else (" ← current" if abs(dd - round(d, 2)) < 1e-9 else "")
                print("| {:.0%}{} | {} | {} | {} | {} | {} |".format(dd, flag, r, pct(ALTMAN_DEFAULT.get(r, 1.0)), money(taxb), money(ebc), money(val)))
